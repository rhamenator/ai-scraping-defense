local policy = dofile("nginx/lua/robots_policy.lua")
local checked = 0
local function check(text, path, expected, ua)
    local actual = policy.is_disallowed(policy.parse(text), path, ua or "ExampleBot/1.0")
    assert(actual == expected, path .. ": expected disallowed=" .. tostring(expected))
    checked = checked + 1
end
local wildcard = "User-agent: *\n"
check(wildcard .. "Disallow: /api/metrics # comment\n", "/api/metrics", true)
check(wildcard .. "Disallow: /static/ # comment\n", "/static/app.js", true)
check(wildcard .. "Disallow: /Admin/\n", "/Admin/", true)
check(wildcard .. "Disallow: /Admin/\n", "/admin/", false)
check(wildcard .. "Disallow: /admin/\n", "/Admin/", false)
check(wildcard .. "Disallow: /admin/\n", "/%61dmin/", true)
check(wildcard .. "Disallow: /%61dmin/\n", "/admin/", true)
check(wildcard .. "Disallow: /a%2fb\n", "/a%2Fb", true)
check(wildcard .. "Disallow: /a%2fb\n", "/a/b", false)
check(wildcard .. "Disallow: /a/b\n", "/a%2Fb", false)
check(wildcard .. "Disallow: /\n", "/", true)
check(wildcard .. "Disallow: /\n", "/anything", true)
check(wildcard .. "Disallow: /\n", "/robots.txt", false)
check(wildcard .. "Disallow: /\n", "/robots.txt?v=1", false)
check(wildcard .. "Disallow: /\nAllow: /public/\n", "/public/page", false)
check(wildcard .. "Allow: /same\nDisallow: /same\n", "/same", false)
check(wildcard .. "Disallow: /same\nAllow: /same\n", "/same", false)
check(wildcard .. "Disallow: /\nAllow: /public/\nDisallow: /public/private\n", "/public/private", true)
check(wildcard .. "Disallow: /*.gif$\n", "/example/image.gif", true)
check(wildcard .. "Disallow: /*.gif$\n", "/example/image.gif?v=1", false)
check(wildcard .. "Disallow: /a*b*c$\n", "/abxbbc", true)
check(wildcard .. "Disallow: /literal%2A\n", "/literal*", true)
check(wildcard .. "Disallow: /literal%24\n", "/literal$", true)
check(wildcard .. "Disallow: /caf\195\169\n", "/caf%C3%A9", true)
check(wildcard .. "Disallow: /caf%C3%A9\n", "/caf\195\169", true)
check(wildcard .. "Disallow: /search?q=private\n", "/search?q=private", true)
check(wildcard .. "Disallow: /admin/\n", "/admin", false)
check(wildcard .. "Disallow: \nAllow: \n", "/anything", false)
check("Disallow: /\n", "/anything", false)
check("\239\187\191USER-AGENT : *\rDISALLOW : /secret # comment\r", "/secret", true)
local groups = wildcard .. "Disallow: /\nUser-agent: ExampleBot\nAllow: /\n"
check(groups, "/anything", false)
check(groups, "/anything", true, "OtherBot")
check("User-agent: ExampleBot\nDisallow: /one\nUser-agent: EXAMPLEBOT\nDisallow: /two\n", "/two", true)
check("User-agent: AnotherBot\nUser-agent: ExampleBot\nDisallow: /one\n", "/one", true)
check("User-agent: ExampleBot\nSitemap: https://example.test/map.xml\nDisallow: /one\n", "/one", true)
check("User-agent: AnotherBot\nDisallow: /\n", "/anything", false)
check(wildcard .. "Disallow: /\nUser-agent: ExampleBot\n", "/anything", false)
check(wildcard .. "Disallow: /\nUser-agent: ExampleBot\nAllow: /\n", "/anything", true, "FakeExampleBot")
print("robots policy: " .. checked .. " RFC 9309 regression cases passed")
